// Production UI checks. Reuses an existing Playwright installation (no project dependency).
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) });
const base = process.env.BASE_URL || 'http://localhost:3100';
const output = process.env.QA_OUTPUT || '/tmp/eyewear-search-favorites-qa';
await mkdir(output, { recursive: true });
const widths = (process.env.QA_WIDTHS || '320,375,430,768,1024,1440').split(',').map(Number);
const variants = { aurora: ['Vinho', 'Preto', 'Tartaruga'], atelier: ['Preto', 'Tartaruga'], atlas: ['Preto', 'Vinho'], alma: ['Tartaruga', 'Preto'], lume: ['Tartaruga', 'Vinho'], linha: ['Preto', 'Vinho'] };
const results = [];
try {
  for (const width of widths) {
    const context = await browser.newContext({ viewport: { width, height: 900 }, hasTouch: width < 1024, isMobile: width < 768 });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    page.on('console', (message) => { if (message.type() === 'error') errors.push(`${message.text()} (${message.location().url})`); });
    page.on('response', (response) => { if (response.status() >= 400 && response.url().includes('/_next/image')) errors.push(`image ${response.status()}: ${response.url()}`); });
    const overflow = async () => assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `overflow at ${width} on ${page.url()}`);
    const close = async (buttonName) => {
      if (buttonName) await page.getByRole('button', { name: buttonName, exact: true }).click();
      else await page.keyboard.press('Escape');
      await page.getByRole('dialog').waitFor({ state: 'detached' });
    };
    const openSearch = async () => {
      await page.getByRole('button', { name: 'Buscar produtos', exact: true }).click();
      await page.waitForFunction(() => document.querySelector('.search-field input') === document.activeElement);
    };
    const input = page.getByRole('searchbox', { name: 'Nome ou tipo de óculos' });
    await page.goto(base);
    await page.waitForTimeout(1300);
    await overflow();
    const before = await page.locator('.hero').boundingBox();
    await page.locator('.site-header').screenshot({ path: `${output}/header-${width}.png` });
    await openSearch();
    await page.waitForTimeout(350);
    assert.equal(await page.locator('.search-chips a').count(), 8);
    assert.equal((await page.locator('.hero').boundingBox()).y, before.y);
    const panel = await page.locator('.search-panel').boundingBox();
    const header = await page.locator('.site-header').boundingBox();
    assert.ok(Math.abs(panel.y - (header.y + header.height)) <= 1);
    await overflow();
    await page.screenshot({ path: `${output}/search-suggestions-${width}.png` });
    await input.fill('aURora');
    assert.equal(await page.locator('.search-results li').count(), 1);
    await page.locator('.search-results img').evaluate((image) => image.decode());
    assert.ok((await page.locator('.search-results img').getAttribute('src')).includes('aurora-frente.webp'));
    assert.ok(await page.locator('.search-results').getByText('Vinho', { exact: true }).isVisible());
    await input.fill('ÓCULOS DE GRAU');
    assert.equal(await page.locator('.search-results li').count(), 3);
    for (const image of await page.locator('.search-results img').all()) await image.evaluate((el) => el.decode());
    await page.waitForTimeout(250);
    await page.screenshot({ path: `${output}/search-results-${width}.png` });
    await input.fill('inexistente');
    assert.ok(await page.getByText('Nenhum produto encontrado.', { exact: true }).isVisible());
    await input.fill('  ');
    assert.equal(await page.locator('.search-chips a').count(), 8);
    await page.keyboard.press('Tab');
    assert.equal(await page.getByRole('button', { name: 'Cancelar', exact: true }).evaluate((el) => el === document.activeElement), true);
    await close('Cancelar');
    await page.waitForFunction(() => document.querySelector('[aria-label="Buscar produtos"]') === document.activeElement);
    await openSearch();
    await close();
    await page.waitForFunction(() => document.querySelector('[aria-label="Buscar produtos"]') === document.activeElement);
    await openSearch();
    await page.locator('.search-backdrop').click({ position: { x: 5, y: 750 } });
    await page.getByRole('dialog').waitFor({ state: 'detached' });
    await openSearch();
    await page.locator('.search-chips').getByRole('link', { name: 'Óculos de sol', exact: true }).click();
    await page.waitForURL('**/produtos?categoria=Sol');
    await page.getByRole('heading', { level: 1, name: 'Óculos de sol', exact: true }).waitFor();
    assert.equal(await page.locator('.product-card').count(), 3);
    await openSearch();
    await input.fill('grau');
    await input.press('Enter');
    await page.waitForURL('**/produtos?q=grau');
    await page.getByRole('heading', { level: 1, name: /Resultados para.*grau/ }).waitFor();
    assert.equal(await page.locator('.product-card').count(), 3);
    await openSearch();
    await input.fill('Aurora');
    await page.getByRole('link', { name: 'Ver Aurora, Vinho', exact: true }).click();
    await page.waitForURL('**/produto/aurora?cor=Vinho');
    // Save two variants from the product page; their hearts must remain independent.
    const detail = page.locator('.pdp-info');
    await page.getByRole('button', { name: 'Favoritar Aurora, Vinho', exact: true }).click();
    await detail.getByRole('button', { name: 'Preto', exact: true }).click();
    await page.getByRole('button', { name: 'Favoritar Aurora, Preto', exact: true }).click();
    await detail.getByRole('button', { name: 'Vinho', exact: true }).click();
    assert.equal(await page.locator('.detail-favorite').getAttribute('aria-pressed'), 'true');
    await page.getByRole('button', { name: 'Favoritos', exact: true }).click();
    await page.waitForTimeout(350);
    const dialog = page.getByRole('dialog');
    assert.ok(await dialog.getByRole('heading', { name: 'Meus favoritos (2)', exact: true }).isVisible());
    assert.equal(await dialog.locator('.favorite-item').count(), 2);
    for (const image of await dialog.locator('img').all()) await image.evaluate((image) => image.decode());
    assert.ok((await dialog.getByRole('link', { name: 'Ver Aurora, Preto', exact: true }).locator('img').getAttribute('src')).includes('aurora-preto-frente'));
    const favoriteBox = await dialog.boundingBox();
    if (width >= 768) {
      const triggerBox = await page.locator('.site-header [aria-label="Favoritos"]').boundingBox();
      assert.ok(Math.abs(favoriteBox.x + favoriteBox.width - triggerBox.x - triggerBox.width) <= 1);
      assert.ok(Math.abs(favoriteBox.y - triggerBox.y - triggerBox.height - 12) <= 1);
      assert.ok(favoriteBox.width >= 340 && favoriteBox.width <= 380);
    } else assert.ok(Math.abs(favoriteBox.y + favoriteBox.height - 900) <= 1);
    await overflow();
    await page.screenshot({ path: `${output}/favorites-two-colors-${width}.png` });
    await dialog.getByRole('link', { name: 'Ver Aurora, Preto', exact: true }).click();
    await page.waitForURL('**/produto/aurora?cor=Preto');
    await detail.getByRole('button', { name: 'Preto', exact: true, pressed: true }).waitFor();
    assert.equal(await detail.getByRole('button', { name: 'Preto', exact: true }).getAttribute('aria-pressed'), 'true');
    await page.reload();
    assert.equal(await page.locator('.detail-favorite').getAttribute('aria-pressed'), 'true');
    await page.getByRole('button', { name: 'Favoritos', exact: true }).click();
    assert.equal(await dialog.locator('.favorite-item').count(), 2);
    await dialog.getByRole('button', { name: 'Remover Aurora, Preto dos favoritos', exact: true }).click();
    assert.equal(await dialog.locator('.favorite-item').count(), 1);
    assert.ok(await dialog.getByRole('link', { name: 'Ver Aurora, Vinho', exact: true }).isVisible());
    await close('Fechar favoritos');
    assert.equal(await page.locator('.detail-favorite').getAttribute('aria-pressed'), 'false');
    // The card reflects the selected color, and toggles only that variant.
    await page.goto(`${base}/produtos`);
    const card = page.locator('.product-card').filter({ has: page.getByRole('heading', { name: 'Aurora', exact: true }) });
    assert.equal(await card.locator('.favorite-button').getAttribute('aria-pressed'), 'true');
    await card.getByRole('button', { name: 'Preto', exact: true }).click();
    assert.equal(await card.locator('.favorite-button').getAttribute('aria-pressed'), 'false');
    await card.locator('.favorite-button').click();
    await card.getByRole('button', { name: 'Vinho', exact: true }).click();
    assert.equal(await card.locator('.favorite-button').getAttribute('aria-pressed'), 'true');
    await page.getByRole('button', { name: 'Favoritos', exact: true }).click();
    await dialog.getByRole('button', { name: 'Remover Aurora, Preto dos favoritos', exact: true }).click();
    await dialog.getByRole('button', { name: 'Remover Aurora, Vinho dos favoritos', exact: true }).click();
    assert.ok(await dialog.getByText('Seus favoritos aparecerão aqui.', { exact: true }).isVisible());
    await page.waitForFunction(() => document.querySelector('[aria-label="Fechar favoritos"]') === document.activeElement);
    await close();
    await page.waitForFunction(() => document.querySelector('[aria-label="Favoritos"]') === document.activeElement);
    await page.getByRole('button', { name: 'Favoritos', exact: true }).click();
    await page.locator('.favorites-backdrop').click({ position: { x: 4, y: 4 } });
    await dialog.waitFor({ state: 'detached' });
    // Persisted fixture exercises long-list scrolling without clicking through all 13 product combinations.
    const allItems = Object.entries(variants).flatMap(([slug, colors]) => colors.map((color) => ({ slug, color })));
    await page.evaluate((items) => localStorage.setItem('oculos-favorites', JSON.stringify({ state: { items }, version: 1 })), allItems);
    await page.reload();
    await page.getByRole('button', { name: 'Favoritos', exact: true }).click();
    await page.waitForTimeout(350);
    assert.equal(await dialog.locator('.favorite-item').count(), 13);
    assert.ok(await page.locator('.favorites-scroll').evaluate((el) => el.scrollHeight > el.clientHeight));
    await page.locator('.favorites-scroll').evaluate((el) => { el.scrollTop = el.scrollHeight; });
    assert.ok(await dialog.getByRole('link', { name: 'Ver Linha, Vinho', exact: true }).isVisible());
    await page.keyboard.press('Tab');
    assert.ok(await dialog.evaluate((el) => el.contains(document.activeElement)));
    await overflow();
    await page.screenshot({ path: `${output}/favorites-scroll-${width}.png` });
    await close();
    await page.getByRole('button', { name: 'Favoritos', exact: true }).click();
    await page.waitForTimeout(350);
    await page.getByRole('button', { name: 'Fechar favoritos', exact: true }).click();
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.locator('.favorites-panel').waitFor({ state: 'detached' });
    await page.locator('.favorites-backdrop').waitFor({ state: 'detached' });
    assert.ok(await page.evaluate(() => !document.body.hasAttribute('data-scroll-locked')));
    await openSearch();
    assert.equal(await page.locator('.search-panel').evaluate((el) => getComputedStyle(el).animationName), 'none');
    await input.fill('sol');
    assert.equal(await page.locator('.search-results li').count(), 3);
    await close();
    await page.getByRole('button', { name: 'Favoritos', exact: true }).click();
    assert.equal(await dialog.evaluate((el) => getComputedStyle(el).animationName), 'none');
    await close();
    assert.deepEqual(errors, []);
    results.push({ width, errors, search: 'suggestions, live names/categories, images, empty, Enter, links, Cancel, Escape, outside, focus, no layout displacement', favorites: 'two colors, PDP/card sync, variant URL, persistence, removal, empty, 13-item scroll, anchoring/sheet, reduced motion' });
    await writeFile(`${output}/results.json`, JSON.stringify(results, null, 2));
    console.log(`Passed ${width}px`);
    await context.close();
  }
  // Exercise actual Zustand v0 migration in the browser (not just the normalization helper).
  const legacy = await browser.newContext({ viewport: { width: 1024, height: 900 } });
  await legacy.addInitScript(() => {
    if (!localStorage.getItem('oculos-favorites')) localStorage.setItem('oculos-favorites', JSON.stringify({ state: { slugs: ['aurora', 'atlas'] }, version: 0 }));
  });
  const page = await legacy.newPage();
  await page.goto(base);
  await page.waitForTimeout(1300);
  await page.getByRole('button', { name: 'Favoritos', exact: true }).click();
  assert.equal(await page.locator('.favorite-item').count(), 2);
  assert.equal(await page.getByText('Cor não registrada', { exact: true }).count(), 2);
  assert.ok(await page.getByText('Imagem de referência: Vinho', { exact: true }).isVisible());
  const persisted = await page.evaluate(() => JSON.parse(localStorage.getItem('oculos-favorites')));
  assert.equal(persisted.version, 1);
  assert.deepEqual(persisted.state.items, [{ slug: 'aurora', color: null }, { slug: 'atlas', color: null }]);
  for (const image of await page.locator('.favorites-panel img').all()) await image.evaluate((image) => image.decode());
  await page.waitForTimeout(350);
  await page.screenshot({ path: `${output}/legacy-migration.png` });
  await page.reload();
  await page.getByRole('button', { name: 'Favoritos', exact: true }).click();
  assert.equal(await page.getByText('Cor não registrada', { exact: true }).count(), 2);
  await legacy.close();
  results.push({ legacyMigration: 'v0 slugs preserved as null-color items in v1 and after reload' });
  await writeFile(`${output}/results.json`, JSON.stringify(results, null, 2));
  console.log(JSON.stringify(results, null, 2));
} finally { await browser.close(); }
